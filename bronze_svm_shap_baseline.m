end


function foldId = makeStratifiedFolds(Y, K, seed)
rng(seed, 'twister');
Y = removecats(categorical(Y));
classes = categories(Y);
N = numel(Y);
foldId = zeros(N,1);
for c = 1:numel(classes)
    idx = find(Y == classes{c});
    idx = idx(randperm(numel(idx)));
    for i = 1:numel(idx)
        foldId(idx(i)) = mod(i-1, K) + 1;
    end
end
end

function [trIdx, valIdx] = makeStratifiedHoldout(Y, holdoutRatio, seed)
rng(seed, 'twister');
Y = removecats(categorical(Y));
classes = categories(Y);
N = numel(Y);
valIdx = false(N,1);
for c = 1:numel(classes)
    idx = find(Y == classes{c});
    idx = idx(randperm(numel(idx)));
    nVal = max(1, round(numel(idx) * holdoutRatio));
    nVal = min(nVal, numel(idx)-1);
    valIdx(idx(1:nVal)) = true;
end
trIdx = ~valIdx;
end

function imp = permutationFeatureImportance(model, X, positiveClass)
[~, baseScoreMat] = predict(model, X);
posCol = find(strcmp(model.ClassNames, positiveClass), 1);
baseScore = mean(baseScoreMat(:, posCol));
imp = zeros(1, size(X,2));
for j = 1:size(X,2)
    Xp = X;
    Xp(:,j) = Xp(randperm(size(X,1)), j);
    [~, s] = predict(model, Xp);
    imp(j) = abs(baseScore - mean(s(:, posCol)));
end
end

function shapMat = normalizeShapValues(shapRaw, expectedFeatureCount)
% Convert various shapley() output formats into numeric [N x P] matrix.
if isnumeric(shapRaw)
    shapMat = shapRaw;
elseif istable(shapRaw)
    numMask = varfun(@isnumeric, shapRaw, 'OutputFormat', 'uniform');
    shapTblNum = shapRaw(:, numMask);
    shapMat = table2array(shapTblNum);
else
    error('Unsupported SHAP value type: %s', class(shapRaw));
end

if ~isnumeric(shapMat) || isempty(shapMat)
    error('SHAP values could not be converted to numeric matrix.');
end

if size(shapMat, 2) ~= expectedFeatureCount
    if size(shapMat, 1) == expectedFeatureCount
        shapMat = shapMat.';
    else
        error('SHAP dimension mismatch: expected %d features, got [%d x %d].', ...
            expectedFeatureCount, size(shapMat, 1), size(shapMat, 2));
    end
end
end